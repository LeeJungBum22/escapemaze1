    const int X = 17;
    const int Y = 11;

    [MenuItem("StageMap/Generate All Maps")]
    public static void GenerateAll()
    {
        if (!AssetDatabase.IsValidFolder("Assets/StageMaps"))
            AssetDatabase.CreateFolder("Assets", "StageMaps");

        string[] robotNames = { "알파(IDA)", "베타(Dij)", "감마(BFS)", "델타(AStar)",
                                 "엡실론(Best)", "제타(OJPS)", "에타(JPS)", "세타(Trace)", "오메가(RL)" };

        for (int robotId = 0; robotId < 9; robotId++)
        {
            if (!AssetDatabase.IsValidFolder($"Assets/StageMaps/{robotNames[robotId]}"))
                AssetDatabase.CreateFolder("Assets/StageMaps", robotNames[robotId]);

            for (int stage = 0; stage < 5; stage++)
            {
                var data = ScriptableObject.CreateInstance<StageMapData>();
                data.robotId = robotId;
                data.stageIndex = stage;
                data.limitTime = GetLimitTime(robotId, stage);
                data.mapData = GetMapData(robotId, stage);

                string path = $"Assets/StageMaps/{robotNames[robotId]}/Stage{stage + 1}.asset";

                // 기존 파일 있으면 덮어쓰기
                var existing = AssetDatabase.LoadAssetAtPath<StageMapData>(path);
                if (existing != null)
                {
                    existing.robotId = data.robotId;
                    existing.stageIndex = data.stageIndex;
                    existing.limitTime = data.limitTime;
                    existing.mapData = data.mapData;
                    EditorUtility.SetDirty(existing);
                }
                else
                {
                    AssetDatabase.CreateAsset(data, path);
                }
            }
        }

        AssetDatabase.SaveAssets();
        Debug.Log("[StageMapGenerator] 45개 맵 생성/갱신 완료! (17x11)");
    }

    static float GetLimitTime(int robotId, int stage)
    {
        float[][] times = new float[][]
        {
            new float[]{ 60f, 50f, 40f, 35f, 30f },
            new float[]{ 50f, 42f, 35f, 28f, 22f },
            new float[]{ 45f, 38f, 32f, 26f, 20f },
            new float[]{ 40f, 34f, 28f, 22f, 18f },
            new float[]{ 35f, 30f, 25f, 20f, 15f },
            new float[]{ 45f, 38f, 30f, 24f, 18f },
            new float[]{ 38f, 32f, 26f, 20f, 15f },
            new float[]{ 30f, 25f, 20f, 16f, 12f },
            new float[]{ 55f, 45f, 38f, 30f, 25f },
        };
        return times[robotId][stage];
    }

    static int[] GetMapData(int robotId, int stage)
    {
        switch (robotId)
        {
            case 0: return IDAStarMap(stage);
            case 1: return DijkstraMap(stage);
            case 2: return BFSMap(stage);
            case 3: return AStarMap(stage);
            case 4: return BestFirstMap(stage);
            case 5: return OJPSMap(stage);
            case 6: return JPSMap(stage);
            case 7: return TraceMap(stage);
            case 8: return RLMap(stage);
            default: return DefaultMap();
        }
    }

