/// <summary>
/// 에디터 전용 맵 생성 도구.
/// 유니티 상단 메뉴 → StageMap → Generate All Maps 클릭하면
/// 45개 ScriptableObject 자동 생성. (17x11)
/// </summary>
public class StageMapGenerator
